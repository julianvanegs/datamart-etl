-- ============================================================
-- Repositorio analitico DataMart - esquema y dimensiones
-- Se ejecuta automaticamente al crear el contenedor dw-postgres.
-- ============================================================
CREATE SCHEMA IF NOT EXISTS dw;
SET search_path TO dw, public;

-- Calendario (fecha en UTC)
CREATE TABLE IF NOT EXISTS dim_date (
    date_key      INTEGER PRIMARY KEY,           -- formato AAAAMMDD
    full_date     DATE    NOT NULL UNIQUE,
    year          SMALLINT NOT NULL,
    quarter       SMALLINT NOT NULL,
    month         SMALLINT NOT NULL,
    year_month    CHAR(7)  NOT NULL,              -- AAAA-MM
    day_of_month  SMALLINT NOT NULL,
    day_of_week   SMALLINT NOT NULL,              -- 1 = lunes ... 7 = domingo
    is_weekend    BOOLEAN  NOT NULL
);

CREATE TABLE IF NOT EXISTS dim_country (
    country_key   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_name  TEXT NOT NULL UNIQUE
);

-- Clientes. La clave 0 representa las compras sin customer ID (decision documentada).
CREATE TABLE IF NOT EXISTS dim_customer (
    customer_key  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   TEXT NOT NULL UNIQUE,
    is_identified BOOLEAN NOT NULL
);
INSERT INTO dim_customer (customer_key, customer_id, is_identified)
OVERRIDING SYSTEM VALUE
VALUES (0, 'ANONYMOUS', FALSE)
ON CONFLICT (customer_key) DO NOTHING;

CREATE TABLE IF NOT EXISTS dim_product (
    product_key               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_code                TEXT NOT NULL UNIQUE,   -- normalizado: mayusculas y sin espacios
    canonical_description     TEXT NOT NULL,
    category                  TEXT NOT NULL,
    category_source           TEXT NOT NULL,          -- 'products_api' | 'keyword_rules'
    supplier_country          TEXT,
    is_active                 BOOLEAN,
    raw_variant_count         INTEGER NOT NULL,       -- descripciones distintas tal como llegaron
    normalized_variant_count  INTEGER NOT NULL,       -- descripciones distintas tras normalizar
    first_seen_utc            TIMESTAMPTZ,
    last_seen_utc             TIMESTAMPTZ,
    updated_at                TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Todas las variantes de descripcion observadas por producto (para auditar consistencia)
CREATE TABLE IF NOT EXISTS product_description_variant (
    product_key      INTEGER NOT NULL REFERENCES dim_product (product_key) ON DELETE CASCADE,
    raw_description  TEXT    NOT NULL,
    occurrences      INTEGER NOT NULL,
    PRIMARY KEY (product_key, raw_description)
);
